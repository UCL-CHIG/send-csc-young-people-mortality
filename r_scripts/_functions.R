# function for saving results from Cox models
cox_plot_fun <- function(data, by_var){
  
cox_all_cause_min_boys <- coxph(Surv(time_risk, data[[by_var]]) ~ sen_csc_flag_group, data = filter(data, sex == "M"))
cox_all_cause_min_boys_tidy <- tidy(cox_all_cause_min_boys, conf.int = T, exp = T) %>% 
  mutate(model = "Minimal") %>%
  mutate(group = "Boys")

cox_all_cause_min_girls <- coxph(Surv(time_risk, data[[by_var]]) ~ sen_csc_flag_group, data = filter(data, sex == "F"))
cox_all_cause_min_girls_tidy <- tidy(cox_all_cause_min_girls, conf.int = T, exp = T) %>% 
  mutate(model = "Minimal") %>%
  mutate(group = "Girls")

min_all <- rbind(cox_all_cause_min_boys_tidy, cox_all_cause_min_girls_tidy)

cox_all_cause_adj_boys <- coxph(Surv(time_risk, data[[by_var]]) ~ sen_csc_flag_group + chronic_condition_pre14 + 
                                  ethnos_mode + idaci_2010_rank_mode + fsm_evereligible, 
                                data = filter(data, sex == "M"))
cox_all_cause_adj_boys_tidy <- tidy(cox_all_cause_adj_boys, conf.int = T, exp = T) %>% 
  mutate(model = "Adjusted") %>%
  mutate(group = "Boys")

cox_all_cause_adj_girls <- coxph(Surv(time_risk, data[[by_var]]) ~ sen_csc_flag_group + chronic_condition_pre14 + 
                                   ethnos_mode + idaci_2010_rank_mode + fsm_evereligible, 
                                 data = filter(data, sex == "F"))
cox_all_cause_adj_girls_tidy <- tidy(cox_all_cause_adj_girls, conf.int = T, exp = T) %>% 
  mutate(model = "Adjusted") %>%
  mutate(group = "Girls")

max_all <- rbind(cox_all_cause_adj_boys_tidy, cox_all_cause_adj_girls_tidy)

min_max <- rbind(min_all, max_all) %>% 
  filter(grepl("sen_csc_flag_group", term)) 

plotall_data <- min_max %>% 
  mutate(var = case_when(term == "sen_csc_flag_groupCSC only" ~ "2. CSC", 
                         term == "sen_csc_flag_groupSEN" ~ "1. SEN",
                         term == "sen_csc_flag_groupSEN and CSC" ~ "3. SEN and CSC")) 

plotall <- plotall_data %>%
  ggplot(aes(x=estimate, y=var)) + 
  geom_point(aes(colour = model), size = 2, position = position_dodge(-.5)) + 
  geom_errorbar(aes(xmin = conf.low, xmax = conf.high, colour = model), position = position_dodge(-.5), width = 0.2) +
  geom_vline(xintercept = 1, linetype = "dashed") + 
  ylab("") +
  coord_trans(x = "log") +
  xlab("Hazard ratio (Log scale)") + 
  scale_color_manual(values = c("hotpink", 
                                "purple")) +
  theme_bw() +
  facet_wrap(~group)

return(plotall)

}

