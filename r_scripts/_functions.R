#statistical mode ignoring NAs, and if multiple return most recent
mode_fun <- function(v) {
  v <- v[!is.na(v)]
  ux <- unique(v)
  tab <- tabulate(match(v, ux))
  md <- ux[tab == max(tab)]
  return(md[length(md)]) # last if multimodal
}


#sdc to suppress and round

sdc_fun <- function(data, n_var){
  
  sdc_data <- data %>% 
    mutate(across(.cols = all_of(n_var), 
                  .fns = ~ ifelse(. < 7, 
                                  NA_real_, 
                                  round(. / 10) * 10))) %>%
    mutate_all(~replace(., is.na(.), "c")) 
           
    return(sdc_data)
}




# crosstab counts

crosstab_exposure_fun <- function(data, by_var){
  
  crosstab <- data %>% 
    group_by(.data[[by_var]], sen_csc_flag) %>% 
    count() %>% 
    rename(group = all_of(by_var)) %>% 
    mutate(group = as.character(group),
           domain= by_var) %>%
    ungroup() %>% 
    select(sen_csc_flag, group, domain, n)
  
  return(crosstab)
}


# function to derive indicators based on diagnostic  (from ania)
indicate_icd  <- function(diag_data, code_list, diag) {
  # diag_data --> operation or diagnostic dataset
  # code list --> list of ICD-10 codes
  # diag --> field to specify if we want to use diagnoses or operations
  
  # clean the code list
  code_list <- data.table(code_list)
  code_list$diag <- gsub("\\.","", code_list$diag )
  code_list[, diag := substr(diag, 1, 4)]
  
  # 3 character codes:
  subgroup_codes3 <- code_list[nchar(diag)==3,] 
  diag_cc3 <-   diag_data[substr(diag, 1, 3) %in% subgroup_codes3$diag]
  
  # 4 letter codes:
  subgroup_codes4 <- code_list[nchar(diag)==4,] 
  diag_cc4 <-   diag_data[substr(diag, 1, 4) %in% subgroup_codes4$diag]
  
  # combine
  diag_cc <- rbind(diag_cc4, diag_cc3)
  return(diag_cc)
}



